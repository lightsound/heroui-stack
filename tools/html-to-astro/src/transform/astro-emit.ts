export function emitBaseLayout(title: string, headExtra: string, stylesheets: string[]): string {
  const linkTags = stylesheets
    .map((href) => `    <link rel="stylesheet" href="${href}" />`)
    .join("\n");
  const headBlock = [headExtra, linkTags].filter(Boolean).join("\n");

  return `---
const title = ${JSON.stringify(title || "Converted site")};
---
<!doctype html>
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <title>{title}</title>
${headBlock ? `${headBlock}\n` : ""}    <slot name="head" />
  </head>
  <body>
    <slot />
  </body>
</html>
`;
}

export function emitPageAstro(
  bodyHtml: string,
  headHtml: string,
  options: { title?: string; imports?: string[] } = {},
): string {
  const imports = [
    'import BaseLayout from "../layouts/BaseLayout.astro";',
    ...(options.imports ?? []),
  ];
  const frontmatter = ["---", ...imports, "---", ""];
  const parts = [...frontmatter];

  if (options.title) {
    parts.push(
      `<Fragment slot="head"><title>${escapeHtmlText(options.title)}</title></Fragment>`,
      "",
    );
  }
  if (headHtml.trim()) {
    parts.push(`<Fragment slot="head">${headHtml}</Fragment>`, "");
  }

  parts.push("<BaseLayout>", bodyHtml.trim(), "</BaseLayout>");

  return parts.join("\n");
}

function escapeHtmlText(value: string): string {
  return value.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
}

