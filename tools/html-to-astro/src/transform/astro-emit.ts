export function emitComponentAstro(
  html: string,
  scopedCss?: string,
  props?: Array<{ name: string }>,
): string {
  const frontmatter = ["---"];
  if (props?.length) {
    frontmatter.push("interface Props {");
    for (const prop of props) {
      frontmatter.push(`  ${prop.name}: string;`);
    }
    frontmatter.push("}");
    frontmatter.push(`const { ${props.map((prop) => prop.name).join(", ")} } = Astro.props;`);
  }
  frontmatter.push("---", "", html.trim());
  const parts = [...frontmatter];
  if (scopedCss?.trim()) {
    parts.push("", "<style>", scopedCss.trim(), "</style>");
  }
  return parts.join("\n");
}

